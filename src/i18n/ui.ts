const TEXT: Record<Locale, UiText> = { en, fr, rw: en };

export const ui = (locale: Locale): UiText => TEXT[locale];

/** A text with "{name}" filled in. */
export const fill = (text: string, values: Record<string, string>) => text.replace(/\{(\w+)\}/g, (_m, k: string) => values[k] ?? '');

/** Date as shown on the site ("12 Oct 2026" / "12 oct. 2026"). */
export function formatDate(iso: string, locale: Locale = 'en'): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat(locale === 'fr' ? 'fr-FR' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(d);
}
